// 真田昌幸（軍配）3頭身・背丈38ドット。斜め前（front）と斜め後ろ（back）。謙信・信長・光義と同じ組み立てで、頭・色・武器を差し替える。
// 目印は、黒い兜の高い金の二本の前立て、赤い緒（軍の色）、生成りの縁の黒い陣羽織、橙の袖、口ひげとあごひげ。軍配の描き方とコマは家康・信玄と同じ（busho.js の fanKit・fanPoses）。common.js・busho.js と一緒に読む
const KS = (() => {
  // 素材の色（暗・影・地・明）
  const R = {
    n: ['#0c0c10', '#191920', '#2a2a34', '#46465a'], // 黒漆の胴・袖・すね当て
    c: ['#141210', '#2a2522', '#3e3833', '#5a514a'], // 黒い陣羽織（胴と分けるため、少し明るい赤みの墨）
    b: ['#8a7a5e', '#bfae8c', '#e2d4b4', '#f4ead2'], // 陣羽織の生成りの縁・帯
    o: ['#5a240c', '#8e3e16', '#c4642a', '#e89050'], // 橙の袖
    p: ['#141210', '#221e1a', '#332d27', '#4a423a'], // 袴
    g: ['#6e4a1c', '#a8782c', '#e0b84e', '#fff0a0'], // 金
    d: ['#0b0b10', '#1e1e26', '#33333f', '#5c5c74'], // 黒（鞘・軍配）
    t: ['#3a2010', '#5c3519', '#7e4c26', '#a3683a'], // 軍配の柄
    r: ['#5e1414', '#9c2a24', '#d14a38', '#f08a6a'], // 赤い緒・結び目・軍配の日の丸（軍の色に塗り替える）
    s: ['#8a5a44', '#c98f6e', '#ecc4a0', '#fde3c8'], // 肌
    C: ['#0c0c10', '#191920', '#2a2a34', '#46465a'], // 兜（手で置いた頭の素材）
  };
  // 手で置いた頭。K 兜の縁 N 兜 M 兜の光 n 兜の影 Y 金の光 G 金 g 金の影 H 髪 S 肌 s 肌の影
  // b 眉 e 白目 E 黒目 B ひげ m 口 r 赤い緒（軍の色）
  const HP = {
    K: '#0c0c10', N: '#2a2a34', M: '#46465a', n: '#191920', Y: '#fff0a0', G: '#e0b84e', g: '#a8782c',
    H: '#1a120e', S: '#ecc4a0', s: '#c98f6e', b: '#1e140e', e: '#f8f4ee', E: '#1c120c', B: '#5a4030', m: '#a04a3c',
    r: R.r[2],
  };
  const HEAD_FRONT = {
    ax: 8.5, ay: 10.5, top: 5,
    rows: [
      '.......Y..Y.......',
      '.......G..G.......',
      '.......G..G.......',
      '.......g..g.......',
      '......KGNNGK......',
      '....KNNGMNGNNK....',
      '..KNNNNgGGgNNNK...',
      '.KnNNNNNNNNNNNNK..',
      'KnNrHHHSSSSSSSSnK.',
      'KnNrHHbbbSSSbbSnK.',
      'KngrHHSeESSSeESnK.',
      '.KnrHSSSSSSSSSsK..',
      '..KrSSSBBBmBBBs...',
      '...rSSSSSSSSSSs...',
      '....rSSSSBBBSs....',
      '......SSSBBBS.....',
      '.........BB.......',
    ],
  };
  const HEAD_BACK = {
    ax: 8.5, ay: 10.5, top: 5,
    rows: [
      '.........Y..Y.....',
      '.........G..G.....',
      '.........G..G.....',
      '.........g..g.....',
      '........KGNNGK....',
      '......KNNGMNGNK...',
      '...KNNNNNNNNNNNK..',
      '..KNNNNNNNNNMNNNK.',
      '.KnNNNNNNNNNNNNNK.',
      'KnggggggggggggggSK',
      'KnnnnnnnnnnnnnnnS.',
      '.Krrrrrrrrrrrrr.s.',
      '....rrrrrrrr......',
    ],
  };
  const CFG = fanCfg(HP); // 体の作りは軍配の3人で同じ（busho.js）
  function draw(view, o = {}) {
    const k = mkBusho(view, o, CFG);
    const { front, poly, line, rect, sode, stampHead } = k;
    // 軍配と腕（busho.js の fanKit）
    const fk = o.fan && fanKit(k, o.fan);
    // 金の縅・鋲（体の上の横の段のうち、黒い胴のマス）
    const gold = (rows, x0, x1) => k.paint(rows, x0, x1, 'n', R.g[1]);

    if (front) {
      k.legs();
      // 奥の腕：軍配を持たない手は腰に下ろす（橙の袖）
      if (fk) fk.farSide();
      // 草摺（橙の格子）・黒い胴・黒い陣羽織と生成りの縁・帯と赤い結び目
      poly([[16, 40], [32, 40], [33, 44.5], [15, 44.5]], 'o');
      poly([[16, 17], [32, 17], [33, 41], [15, 41]], 'n');
      poly([[14, 17], [21, 17], [20.5, 42.5], [13, 42.5]], 'c');
      poly([[28, 17], [34, 17], [35, 42.5], [28.5, 42.5]], 'c');
      line(20.5, 17, 20, 42, 'b', 1.4);
      line(28.5, 17, 29, 42, 'b', 1.4);
      line(13, 42.5, 20.5, 42.5, 'b', 1.2);
      line(28.5, 42.5, 35, 42.5, 'b', 1.2);
      poly([[15, 29.5], [33, 29.5], [33.5, 31.5], [15, 31.5]], 'b');
      k.ell(24.5, 30.5, 1.4, 1.2, 'r');
      sode(33, 21, 2.8);
      // 腰の刀
      line(29, 32, 36, 37, 'd', 2); rect(28, 31, 2, 2, 'g');
      // 黒の立て襟
      poly([[17, 13], [31, 13], [32, 17], [29, 19], [19, 19], [16, 17]], 'n');
      stampHead(HEAD_FRONT);
      if (fk) fk.nearSide();
      sode(15, 20, 4.2);
      gold([22, 25], 9, 21);
      gold([35, 38], 21, 28);
    } else {
      k.legs();
      // 奥の腕：待機は軍配を握る、攻撃は腰に下ろす
      if (fk) fk.farSide();
      // 草摺・黒い陣羽織の背と生成りの縁
      poly([[14, 40], [34, 40], [35, 44.5], [13, 44.5]], 'o');
      poly([[13, 17], [35, 17], [36, 43], [12, 43]], 'c');
      line(12, 43, 36, 43, 'b', 1.2);
      // 背の上の四角い開きから見える黒い胴と金の鋲
      poly([[19, 17], [29, 17], [29, 23], [19, 23]], 'n');
      gold([19.5, 22], 20, 29);
      // 帯と、背の結び目・垂れた2本の端（生成り）
      poly([[12.5, 29.5], [35.5, 29.5], [36, 31.5], [12.5, 31.5]], 'b');
      k.ell(24, 30.5, 2, 1.6, 'b');
      line(23, 31, 20.5, 38, 'b', 1.6);
      line(25, 31, 27.5, 38, 'b', 1.6);
      // 腰の刀（左の腰から手前へ）
      line(17, 33, 6, 43, 'd', 2); rect(4, 43, 3, 2, 'g');
      sode(13, 20, 2.8); sode(34, 20, 4.2);
      gold([22, 25], 8, 18);
      gold([22, 25], 30, 41);
      // 首の後ろの赤い布（軍の色）。兜の錣と肩のあいだを埋める
      poly([[17, 12], [31, 12], [30.5, 15], [28, 16.5], [20, 16.5], [17.5, 15]], 'r');
      poly([[17.5, 15], [30.5, 15], [33, 17], [15, 17]], 'n');
      stampHead(HEAD_BACK);
      if (fk) fk.nearSide();
    }
    // 仕上げ（busho.js の fanFinish）。スキルの溜めは、軍配のまわりを赤みの火の色に光らせる（家康の金の光と見分けるため。外側は袖の橙を使い、色の数を抑える）
    return fanFinish(k, fk, o, R, ['#ff6a3c', R.o[2]]);
  }
  // 待機・歩き・攻撃・スキル・被弾・倒れは3人とも同じ（busho.js の fanPoses）
  return bushoFrames(R, (v) => fanPoses(draw, v));
})();
